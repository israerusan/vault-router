import esbuild from "esbuild";
    import process from "process";
    import { builtinModules as builtins } from "node:module";

    const banner = `/*
This file is auto-generated by esbuild. Edit the source in src/ instead.
Vault Router
*/`;
    const prod = process.argv[2] === "production";

    const context = await esbuild.context({
      banner: { js: banner },
      entryPoints: ["src/main.ts"],
      bundle: true,
      external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtins
      ],
      format: "cjs",
      target: "es2018",
      logLevel: "info",
      sourcemap: prod ? false : "inline",
      treeShaking: true,
      outfile: "main.js",
      platform: "browser"
    });

    if (prod) {
      await context.rebuild();
      process.exit(0);
    } else {
      await context.watch();
    }
